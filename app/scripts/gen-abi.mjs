// Regenerates src/lib/abi.ts from Foundry's build output, so the console always matches
// the contracts it talks to. Run `forge build` at the repo root first, then `npm run abi`.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const out = resolve(here, '../../out')
const target = resolve(here, '../src/lib/abi.ts')

const load = (name) => JSON.parse(readFileSync(resolve(out, `${name}.sol/${name}.json`), 'utf8')).abi

const pick = (abi, names) => {
  const items = abi.filter((x) => x.type === 'function' && names.includes(x.name))
  const missing = names.filter((n) => !items.some((x) => x.name === n))
  if (missing.length) throw new Error(`ABI is missing: ${missing.join(', ')}`)
  return items
}
const errors = (abi) => abi.filter((x) => x.type === 'error')
const uniq = (items) => {
  const seen = new Set()
  return items.filter((x) => {
    const key = `${x.type}:${x.name}:${(x.inputs ?? []).map((i) => i.type).join(',')}`
    return seen.has(key) ? false : (seen.add(key), true)
  })
}

const repo = load('RepoDvP')
const eur = load('nhEUR')
const bond = load('nhBOND')
const oracle = load('nhNAVOracle')
const registry = load('IdentityRegistry')
const identityArtifact = JSON.parse(readFileSync(resolve(out, 'Identity.sol/Identity.json'), 'utf8'))

const tokenViews = ['balanceOf', 'allowance', 'approve', 'decimals', 'symbol', 'isFrozen', 'paused']

const sections = {
  // RepoDvP plus every custom error a nested call can bubble up through SafeERC20,
  // so reverts from the tokens and the oracle decode to a name instead of raw bytes.
  repoDvpAbi: uniq([...repo, ...errors(eur), ...errors(oracle)]),
  cashTokenAbi: uniq([...pick(eur, [...tokenViews, 'identityRegistry', 'mint', 'hasRole', 'TREASURY_ROLE']), ...errors(eur)]),
  bondTokenAbi: uniq([...pick(bond, [...tokenViews, 'getFrozenTokens', 'isEligibleInvestor', 'identityRegistry', 'issue', 'isAgent']), ...errors(bond)]),
  oracleAbi: uniq([
    ...pick(oracle, ['latestRoundData', 'decimals', 'description', 'updateNAV', 'hasRole', 'CALCULATION_AGENT_ROLE']),
    ...oracle.filter((x) => x.type === 'event' || x.type === 'error'),
  ]),
  identityRegistryAbi: uniq([
    ...pick(registry, ['isVerified', 'identity', 'investorCountry', 'contains', 'registerIdentity', 'deleteIdentity', 'isAgent']),
    ...registry.filter((x) => x.type === 'event' && ['IdentityRegistered', 'IdentityRemoved'].includes(x.name)),
  ]),
  // ONCHAINID identity contract, deployed per wallet by the Identity tab: constructor(initialManagementKey, isLibrary).
  identityAbi: identityArtifact.abi.filter((x) => x.type === 'constructor'),
}

const body = Object.entries(sections)
  .map(([name, abi]) => `export const ${name} = ${JSON.stringify(abi, null, 2)} as const\n`)
  .join('\n')

const bytecode = `export const identityBytecode = '${identityArtifact.bytecode.object}' as const\n`
writeFileSync(target, `// Generated by scripts/gen-abi.mjs from ../out. Do not edit by hand: run \`npm run abi\`.\n\n${body}\n${bytecode}`)
console.log(`Wrote ${target}`)
